function getEl<K extends keyof typeof elTags>(id: K): ElOf<(typeof elTags)[K]> {
  const el = document.querySelector<ElOf<(typeof elTags)[K]>>(`#${CSS.escape(id)}`);
  if (el === null) {
    throw new Error(`Missing element: ${id}`);
  }
  return el;
}

